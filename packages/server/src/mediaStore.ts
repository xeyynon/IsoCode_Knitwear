import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

/**
 * Where photo bytes live. The database holds only the key. Disk and memory are here; the S3-compatible
 * store for production (an Indian region) is in s3Store.ts and is chosen by environment variables
 * (mediaFromEnv.ts). Every store streams through the authenticated API: no caller is ever given a bucket address.
 */
export interface MediaStore {
  put(key: string, bytes: Buffer): Promise<void>
  get(key: string): Promise<Buffer | null>
  delete(key: string): Promise<void>
}

/**
 * The one rule for a media key, shared by every store so they refuse the same things: relative, plain
 * characters, no empty or dot segments, nothing that could climb out of a folder or a bucket prefix.
 * Throws the same plain error whatever was wrong; the key is never echoed back.
 */
export function assertMediaKey(key: string): void {
  const ok = typeof key === 'string' && key.length > 0 && key.length <= 200
    && /^[A-Za-z0-9_][A-Za-z0-9/_.-]*$/.test(key) && !key.includes('..')
    && key.split('/').every((seg) => seg !== '' && seg !== '.')
  if (!ok) throw new Error('bad media key')
}

/** Plain files in one folder. Keys are generated by the server (random), never taken from a caller. */
export function diskStore(dir: string): MediaStore {
  const root = path.resolve(dir)
  const file = (key: string) => {
    // Relative keys of plain characters only, and the final path must still be inside the folder.
    assertMediaKey(key)
    const full = path.resolve(root, key)
    if (!full.startsWith(root + path.sep)) throw new Error('bad media key')
    return full
  }
  return {
    async put(key, bytes) { const f = file(key); await mkdir(path.dirname(f), { recursive: true }); await writeFile(f, bytes) },
    async get(key) {
      const f = file(key)
      try { return await readFile(f) } catch (e) {
        // Only "there is no such file" is null. A folder where the file should be, no permission, too many open files or a disk fault are
        // errors: the route answers 500 and the server logs the cause, instead of every photo quietly reading as gone.
        const code = (e as NodeJS.ErrnoException | null)?.code
        if (code === 'ENOENT' || code === 'ENOTDIR') return null
        throw e
      }
    },   // a bad key is an error; a file that is not there is null
    async delete(key) { await rm(file(key), { force: true }) },
  }
}

export function memoryMediaStore(): MediaStore & { files: Map<string, Buffer> } {
  const files = new Map<string, Buffer>()
  return {
    files,
    async put(key, bytes) { assertMediaKey(key); files.set(key, Buffer.from(bytes)) },
    async get(key) { assertMediaKey(key); return files.get(key) ?? null },
    async delete(key) { assertMediaKey(key); files.delete(key) },
  }
}
